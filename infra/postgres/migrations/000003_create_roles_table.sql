CREATE TABLE roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    name TEXT NOT NULL UNIQUE,
    system_key TEXT UNIQUE,
    all_permissions BOOLEAN NOT NULL DEFAULT FALSE,
    can_read_project BOOLEAN NOT NULL DEFAULT FALSE,
    can_update_project BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete_project BOOLEAN NOT NULL DEFAULT FALSE,
    can_manage_members BOOLEAN NOT NULL DEFAULT FALSE,
    can_create_model BOOLEAN NOT NULL DEFAULT FALSE,
    can_read_model BOOLEAN NOT NULL DEFAULT FALSE,
    can_update_model BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete_model BOOLEAN NOT NULL DEFAULT FALSE,
    can_start_model BOOLEAN NOT NULL DEFAULT FALSE,
    can_stop_model BOOLEAN NOT NULL DEFAULT FALSE
);

